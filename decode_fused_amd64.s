// C2D converts ASCII base58 characters to digits and accumulates an invalid
// byte mask. The validation lookup leaves a one-hot character-class bit in
// t2; reuse it to select the ASCII base instead of repeating five threshold
// comparisons. Y13/Y14 are nibble tables, Y15 is 0x0f, and Y12 is zero.
#define FUSED_C2D(v, t1, t2, bad) \
	VPAND Y15, v, t1;                        VPSHUFB t1, Y13, t2; \
	VPSRLW $4, v, Y10;                       VPAND Y15, Y10, Y10; VPSHUFB Y10, Y14, Y10; \
	VPAND Y10, t2, t2;                       VPCMPEQB Y12, t2, Y10; VPOR Y10, bad, bad; \
	VPSHUFB t2, Y7, Y10;                     VPSHUFB t1, Y6, t1; \
	VPAND t2, t1, t1;                        VPCMPEQB Y12, t1, t1; \
	VPADDB ·decFusedB1(SB), t1, t1;          VPADDB t1, Y10, Y10; \
	VPSUBB Y10, v, v

// Three groups of five digits per 128-bit lane become three dword limbs.
#define FUSED_HORNER(v, p, q) \
	VPSHUFB Y8, v, p; VPSHUFB Y9, v, q; \
	VPMADDUBSW Y10, p, p; VPMADDWD Y11, p, p; VPMULLD Y12, p, p; VPADDD q, p, p

// func decode32FusedAVX2(s *byte, n int, dst *[32]byte) int
// Frame: 0 im dwords, 64 bin[8]u64.
TEXT ·decode32FusedAVX2(SB), NOSPLIT, $128-32
	MOVQ s+0(FP), SI
	MOVQ n+8(FP), CX
	MOVQ dst+16(FP), DI
	MOVQ $45, R8
	SUBQ CX, R8

	VMOVDQU (SI), X0
	LEAQ 15(SI), AX
	SUBQ R8, AX
	VINSERTI128 $1, (AX), Y0, Y0
	VBROADCASTI128 -16(SI)(CX*1), Y1

	VMOVDQU ·decFusedLoNib(SB), Y13
	VMOVDQU ·decFusedHiNib(SB), Y14
	VMOVDQU ·decFusedB15(SB), Y15
	VMOVDQU ·decFusedBase(SB), Y7
	VMOVDQU ·decFusedCorr(SB), Y6
	VPXOR Y12, Y12, Y12
	VPXOR Y11, Y11, Y11
	FUSED_C2D(Y0, Y8, Y9, Y11)
	FUSED_C2D(Y1, Y8, Y9, Y11)
	VPMOVMSKB Y11, AX
	TESTL AX, AX
	JNZ fusedInvalid32

	MOVQ R8, X8
	VPBROADCASTB X8, X8
	VMOVDQU ·decFusedIota(SB), Y9
	VPSUBB Y8, Y9, Y9
	VPSHUFB Y9, Y0, Y0
	VPSRLDQ $1, Y1, Y1

	VMOVDQU ·decFusedP(SB), Y8
	VMOVDQU ·decFusedQ(SB), Y9
	VMOVDQU ·decFusedW1(SB), Y10
	VMOVDQU ·decFusedW2(SB), Y11
	VMOVDQU ·decFusedD58(SB), Y12
	FUSED_HORNER(Y0, Y2, Y3)
	FUSED_HORNER(Y1, Y4, Y5)
	VMOVDQU Y2, 0(SP)
	VMOVDQU Y4, 32(SP)

	LEAQ ·decFusedTable32(SB), DX
	VPXOR Y2, Y2, Y2
	VPXOR Y3, Y3, Y3
	VPBROADCASTD 0(SP), Y8
	VPMULUDQ 0(DX), Y8, Y9; VPADDQ Y9, Y2, Y2
	VPMULUDQ 32(DX), Y8, Y9; VPADDQ Y9, Y3, Y3
	VPBROADCASTD 4(SP), Y8
	VPMULUDQ 64(DX), Y8, Y9; VPADDQ Y9, Y2, Y2
	VPMULUDQ 96(DX), Y8, Y9; VPADDQ Y9, Y3, Y3
	VPBROADCASTD 8(SP), Y8
	VPMULUDQ 128(DX), Y8, Y9; VPADDQ Y9, Y2, Y2
	VPMULUDQ 160(DX), Y8, Y9; VPADDQ Y9, Y3, Y3
	VPBROADCASTD 16(SP), Y8
	VPMULUDQ 192(DX), Y8, Y9; VPADDQ Y9, Y2, Y2
	VPMULUDQ 224(DX), Y8, Y9; VPADDQ Y9, Y3, Y3
	VPBROADCASTD 20(SP), Y8
	VPMULUDQ 288(DX), Y8, Y9; VPADDQ Y9, Y3, Y3
	VPBROADCASTD 24(SP), Y8
	VPMULUDQ 352(DX), Y8, Y9; VPADDQ Y9, Y3, Y3
	VPBROADCASTD 32(SP), Y8
	VPMULUDQ 416(DX), Y8, Y9; VPADDQ Y9, Y3, Y3
	VPBROADCASTD 36(SP), Y8
	VPMULUDQ 480(DX), Y8, Y9; VPADDQ Y9, Y3, Y3
	VPBROADCASTD 40(SP), Y8
	VPMULUDQ 544(DX), Y8, Y9; VPADDQ Y9, Y3, Y3
	VMOVDQU Y2, 64(SP)
	VMOVDQU Y3, 96(SP)

	MOVL 120(SP), AX; BSWAPL AX; MOVL AX, 28(DI)
	CLC
	MOVL 112(SP), AX; ADCL 124(SP), AX; BSWAPL AX; MOVL AX, 24(DI)
	MOVL 104(SP), AX; ADCL 116(SP), AX; BSWAPL AX; MOVL AX, 20(DI)
	MOVL 96(SP), AX; ADCL 108(SP), AX; BSWAPL AX; MOVL AX, 16(DI)
	MOVL 88(SP), AX; ADCL 100(SP), AX; BSWAPL AX; MOVL AX, 12(DI)
	MOVL 80(SP), AX; ADCL 92(SP), AX; BSWAPL AX; MOVL AX, 8(DI)
	MOVL 72(SP), AX; ADCL 84(SP), AX; BSWAPL AX; MOVL AX, 4(DI)
	MOVL 64(SP), AX; ADCL 76(SP), AX; BSWAPL AX; MOVL AX, 0(DI)
	MOVL 68(SP), AX; ADCL $0, AX; JNZ fusedTooLarge32
	JMP fusedValidate32

fusedInvalid32:
	MOVQ $1, ret+24(FP)
	VZEROUPPER
	RET
fusedTooLarge32:
	MOVQ $2, ret+24(FP)
	VZEROUPPER
	RET
fusedValidate32:
	CMPB (SI), $49
	JEQ fusedNeedsZeros32
	CMPB (DI), $0
	JEQ fusedNeedsZeros32
	XORL AX, AX
	MOVQ AX, ret+24(FP)
	VZEROUPPER
	RET
fusedNeedsZeros32:
	MOVQ $4, ret+24(FP)
	VZEROUPPER
	RET

