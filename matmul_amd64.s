	IMULQ	BX, AX
	ADDQ	AX, R14
	MOVL	220(DX), AX
	IMULQ	BX, AX
	ADDQ	AX, R15

	// Row 7: bin[7], k=7 only
	MOVL	28(SI), BX
	BSWAPL	BX
	MOVL	252(DX), AX
	IMULQ	BX, AX
	ADDQ	AX, R15

	// Store intermediate[0..8]. intermediate[0] = 0.
	MOVQ	$0, 0(DI)
	MOVQ	R8, 8(DI)
	MOVQ	R9, 16(DI)
	MOVQ	R10, 24(DI)
	MOVQ	R11, 32(DI)
	MOVQ	R12, 40(DI)
	MOVQ	R13, 48(DI)
	MOVQ	R14, 56(DI)
	MOVQ	R15, 64(DI)
	RET

// func decodeMatMul32Scalar(intermediate *[9]uint64, bin *[8]uint64)
