// func encodeMatMul32AVX2(src *[32]byte, intermediate *[9]uint64)
//
// AVX2 encode matmul for 32-byte inputs. Broadcast each big-endian source
// word (byte-swapped in-register via VPSHUFB), multiply against 4 table
// columns per VPMULUDQ. Accumulators Y0-Y1 store intermediate[1..8].
TEXT ·encodeMatMul32AVX2(SB), NOSPLIT, $0-16
	MOVQ	src+0(FP), SI
	MOVQ	intermediate+8(FP), DI
	LEAQ	·encWide32(SB), DX
	VPXOR	Y0, Y0, Y0
	VPXOR	Y1, Y1, Y1
	VMOVDQU	bswapd<>(SB), Y7

	// Row 0
	VPBROADCASTD	0(SI), Y2
	VPSHUFB	Y7, Y2, Y2
	VPMULUDQ	0(DX), Y2, Y3
	VPADDQ	Y3, Y0, Y0
	VPMULUDQ	32(DX), Y2, Y3
	VPADDQ	Y3, Y1, Y1

	// Row 1
	VPBROADCASTD	4(SI), Y2
	VPSHUFB	Y7, Y2, Y2
	VPMULUDQ	64(DX), Y2, Y3
	VPADDQ	Y3, Y0, Y0
	VPMULUDQ	96(DX), Y2, Y3
	VPADDQ	Y3, Y1, Y1

	// Row 2
	VPBROADCASTD	8(SI), Y2
	VPSHUFB	Y7, Y2, Y2
	VPMULUDQ	128(DX), Y2, Y3
	VPADDQ	Y3, Y0, Y0
	VPMULUDQ	160(DX), Y2, Y3
	VPADDQ	Y3, Y1, Y1

	// Row 3
	VPBROADCASTD	12(SI), Y2
	VPSHUFB	Y7, Y2, Y2
	VPMULUDQ	192(DX), Y2, Y3
	VPADDQ	Y3, Y0, Y0
	VPMULUDQ	224(DX), Y2, Y3
	VPADDQ	Y3, Y1, Y1

	// Row 4
	VPBROADCASTD	16(SI), Y2
	VPSHUFB	Y7, Y2, Y2
	VPMULUDQ	288(DX), Y2, Y3
	VPADDQ	Y3, Y1, Y1

	// Row 5
	VPBROADCASTD	20(SI), Y2
	VPSHUFB	Y7, Y2, Y2
	VPMULUDQ	352(DX), Y2, Y3
	VPADDQ	Y3, Y1, Y1

	// Row 6
	VPBROADCASTD	24(SI), Y2
	VPSHUFB	Y7, Y2, Y2
	VPMULUDQ	416(DX), Y2, Y3
	VPADDQ	Y3, Y1, Y1

	// Row 7
	VPBROADCASTD	28(SI), Y2
	VPSHUFB	Y7, Y2, Y2
	VPMULUDQ	480(DX), Y2, Y3
	VPADDQ	Y3, Y1, Y1

	VMOVDQU	Y0, 8(DI)
	VMOVDQU	Y1, 40(DI)
	VZEROUPPER
	RET

// func decodeMatMul32AVX2(intermediate *[9]uint64, bin *[8]uint64)
//
// AVX2 decode matmul for 32-byte outputs. intermediate values are < 58^5
// so broadcasting the low 32 bits of each u64 is exact (VPMULUDQ ignores
// the high lane halves). Accumulators Y0-Y1 store bin[0..7].
TEXT ·decodeMatMul32AVX2(SB), NOSPLIT, $0-16
	MOVQ	intermediate+0(FP), SI
	MOVQ	bin+8(FP), DI
	LEAQ	·decWide32(SB), DX
	VPXOR	Y0, Y0, Y0
	VPXOR	Y1, Y1, Y1

	// Row 0
	VPBROADCASTD	0(SI), Y2
	VPMULUDQ	0(DX), Y2, Y3
	VPADDQ	Y3, Y0, Y0
	VPMULUDQ	32(DX), Y2, Y3
	VPADDQ	Y3, Y1, Y1

