// func digitsToChars8(v *uint64, out *byte)
//
// Converts 8 base-58^5 values (each < 58^5) into 40 base58 chars:
// per 4-lane block, four exhaustively-verified magic divisions split each
// value into 5 digits, VPSHUFB packs them into byte order, and the alphabet
// mapping is applied as chars = d + 49 + sum(a_k * [d > t_k]).
// Writes 16-byte stores at out+0/+10/+20/+30: bytes 0..39 are the chars,
// bytes 40..45 are garbage the caller must overwrite or ignore.
TEXT ·digitsToChars8(SB), NOSPLIT, $0-16
	MOVQ	v+0(FP), SI
	MOVQ	out+8(FP), DI
	VPBROADCASTQ	b58m4<>(SB), Y15
	VPBROADCASTQ	b58d4<>(SB), Y14
	VPBROADCASTQ	b58m3<>(SB), Y13
	VPBROADCASTQ	b58d3<>(SB), Y12
	VPBROADCASTQ	b58m2<>(SB), Y11
	VPBROADCASTQ	b58d2<>(SB), Y10
	VPBROADCASTQ	b58m1<>(SB), Y9
	VPBROADCASTQ	b58d1<>(SB), Y8

	// Block 0: elements 0..3
	VMOVDQU	0(SI), Y0
	VPMULUDQ	Y15, Y0, Y1
	VPSRLQ	$53, Y1, Y1
	VPMULUDQ	Y14, Y1, Y2
	VPSUBQ	Y2, Y0, Y0
	VPMULUDQ	Y13, Y0, Y2
	VPSRLQ	$41, Y2, Y2
	VPMULUDQ	Y12, Y2, Y3
	VPSUBQ	Y3, Y0, Y0
	VPMULUDQ	Y11, Y0, Y3
	VPSRLQ	$32, Y3, Y3
	VPMULUDQ	Y10, Y3, Y4
	VPSUBQ	Y4, Y0, Y0
	VPMULUDQ	Y9, Y0, Y4
	VPSRLQ	$32, Y4, Y4
	VPMULUDQ	Y8, Y4, Y5
	VPSUBQ	Y5, Y0, Y0
	// digits: Y1=d0 Y2=d1 Y3=d2 Y4=d3 Y0=d4; pack into byte order
	VPSHUFB	b58shuf0<>(SB), Y1, Y1
	VPSHUFB	b58shuf1<>(SB), Y2, Y2
	VPSHUFB	b58shuf2<>(SB), Y3, Y3
	VPSHUFB	b58shuf3<>(SB), Y4, Y4
	VPSHUFB	b58shuf4<>(SB), Y0, Y0
	VPOR	Y2, Y1, Y1
	VPOR	Y4, Y3, Y3
	VPOR	Y3, Y1, Y1
	VPOR	Y0, Y1, Y1
	// chars = d + 49 + piecewise alphabet offsets
	VPADDB	b58c49<>(SB), Y1, Y2
	VPCMPGTB	b58thr0<>(SB), Y1, Y6
	VPAND	b58add0<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VPCMPGTB	b58thr1<>(SB), Y1, Y6
	VPAND	b58add1<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VPCMPGTB	b58thr2<>(SB), Y1, Y6
	VPAND	b58add2<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VPCMPGTB	b58thr3<>(SB), Y1, Y6
	VPAND	b58add3<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VPCMPGTB	b58thr4<>(SB), Y1, Y6
	VPAND	b58add4<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VMOVDQU	X2, 0(DI)
	VEXTRACTI128	$1, Y2, X2
	VMOVDQU	X2, 10(DI)

	// Block 1: elements 4..7
	VMOVDQU	32(SI), Y0
	VPMULUDQ	Y15, Y0, Y1
	VPSRLQ	$53, Y1, Y1
	VPMULUDQ	Y14, Y1, Y2
	VPSUBQ	Y2, Y0, Y0
	VPMULUDQ	Y13, Y0, Y2
	VPSRLQ	$41, Y2, Y2
	VPMULUDQ	Y12, Y2, Y3
	VPSUBQ	Y3, Y0, Y0
	VPMULUDQ	Y11, Y0, Y3
	VPSRLQ	$32, Y3, Y3
	VPMULUDQ	Y10, Y3, Y4
	VPSUBQ	Y4, Y0, Y0
	VPMULUDQ	Y9, Y0, Y4
	VPSRLQ	$32, Y4, Y4
	VPMULUDQ	Y8, Y4, Y5
	VPSUBQ	Y5, Y0, Y0
	// digits: Y1=d0 Y2=d1 Y3=d2 Y4=d3 Y0=d4; pack into byte order
	VPSHUFB	b58shuf0<>(SB), Y1, Y1
	VPSHUFB	b58shuf1<>(SB), Y2, Y2
	VPSHUFB	b58shuf2<>(SB), Y3, Y3
	VPSHUFB	b58shuf3<>(SB), Y4, Y4
	VPSHUFB	b58shuf4<>(SB), Y0, Y0
	VPOR	Y2, Y1, Y1
	VPOR	Y4, Y3, Y3
	VPOR	Y3, Y1, Y1
	VPOR	Y0, Y1, Y1
	// chars = d + 49 + piecewise alphabet offsets
	VPADDB	b58c49<>(SB), Y1, Y2
	VPCMPGTB	b58thr0<>(SB), Y1, Y6
	VPAND	b58add0<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VPCMPGTB	b58thr1<>(SB), Y1, Y6
	VPAND	b58add1<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VPCMPGTB	b58thr2<>(SB), Y1, Y6
	VPAND	b58add2<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VPCMPGTB	b58thr3<>(SB), Y1, Y6
	VPAND	b58add3<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VPCMPGTB	b58thr4<>(SB), Y1, Y6
	VPAND	b58add4<>(SB), Y6, Y6
	VPADDB	Y6, Y2, Y2
	VMOVDQU	X2, 20(DI)
	VEXTRACTI128	$1, Y2, X2
	VMOVDQU	X2, 30(DI)

	VZEROUPPER
	RET

