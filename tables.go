// encRowBounds64/decRowBounds64 hold the [first, last) non-zero column of
// each encTable64/decTable64 row, computed once at init. The tables are
// roughly triangular — about half their entries are zero — so the bounded
// matmul loops skip ~2x the work.
var (
	encRowBounds64 [binarySz64][2]int8
	decRowBounds64 [intermediateSz64][2]int8
)

// base58Pairs[x] holds the two base58 chars of x < 58^2, packed for a
// little-endian uint16 store: low byte = chars[x/58] (more significant
// digit), high byte = chars[x%58]. Digit extraction emits two chars per
// constant division instead of one.
var base58Pairs [3364]uint16

// base58InverseFull maps any byte to its base58 digit value, or
// base58InvalidDigit. Valid digits are <= 57 (bits 6-7 clear), so an OR
// accumulator over a run of lookups is >= 64 iff any char was invalid —
// one branch validates a whole group.
var base58InverseFull [256]uint8

func init() {
	for x := range base58Pairs {
		base58Pairs[x] = uint16(base58Chars[x%58])<<8 | uint16(base58Chars[x/58])
	}
	for i := range base58InverseFull {
		base58InverseFull[i] = base58InvalidDigit
	}
	for d, c := range base58Chars {
		base58InverseFull[c] = uint8(d)
	}
	for i := range encTable64 {
		lo, hi := 0, len(encTable64[i])
		for lo < hi && encTable64[i][lo] == 0 {
			lo++
		}
		for hi > lo && encTable64[i][hi-1] == 0 {
			hi--
		}
		encRowBounds64[i] = [2]int8{int8(lo), int8(hi)}
	}
	for i := range decTable64 {
		lo, hi := 0, len(decTable64[i])
		for lo < hi && decTable64[i][lo] == 0 {
			lo++
		}
		for hi > lo && decTable64[i][hi-1] == 0 {
			hi--
		}
		decRowBounds64[i] = [2]int8{int8(lo), int8(hi)}
	}
}

